"""Generate docs/project/TRACEABILITY.md from requirements.yaml and test markers.

Usage:
    uv run python scripts/gen_traceability.py          # write the file
    uv run python scripts/gen_traceability.py --check  # exit 1 if the file is stale

Collects ``@pytest.mark.req(...)`` markers by running pytest in collect-only mode
(including live tests), so the matrix lists every test that verifies each requirement.
"""

from __future__ import annotations

import argparse
import sys
from collections import defaultdict
from pathlib import Path

import pytest
import yaml

ROOT = Path(__file__).resolve().parent.parent
REQUIREMENTS = ROOT / "docs" / "project" / "requirements.yaml"
OUTPUT = ROOT / "docs" / "project" / "TRACEABILITY.md"


class _Collector:
    def __init__(self) -> None:
        self.tests: dict[str, list[str]] = defaultdict(list)

    def pytest_collection_modifyitems(self, items) -> None:
        for item in items:
            for marker in item.iter_markers(name="req"):
                for req_id in marker.args:
                    self.tests[str(req_id)].append(item.nodeid)


def collect() -> dict[str, list[str]]:
    collector = _Collector()
    code = pytest.main(
        ["--collect-only", "-qq", "-m", "", "-p", "no:cacheprovider", str(ROOT / "tests")],
        plugins=[collector],
    )
    if code not in (0, 5):  # 5 = no tests collected
        raise SystemExit(f"pytest collection failed with exit code {code}")
    return collector.tests


def render(reqs: list[dict], tests: dict[str, list[str]]) -> str:
    lines = [
        "# Requirements Traceability Matrix",
        "",
        "Generated by `scripts/gen_traceability.py` from",
        "[`requirements.yaml`](requirements.yaml) and the `@pytest.mark.req` markers in",
        "`tests/`. Do not edit by hand; run the script after changing requirements or tests.",
        "",
    ]
    by_status: dict[str, int] = defaultdict(int)
    for r in reqs:
        by_status[r["status"]] += 1
    tested = sum(1 for r in reqs if tests.get(r["id"]))
    lines += [
        f"**Requirements:** {len(reqs)} · **with at least one test:** {tested} · "
        + " · ".join(f"**{k}:** {v}" for k, v in sorted(by_status.items())),
        "",
        "| ID | Requirement | Priority | Verification | Design | Status | Tests |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in reqs:
        names = tests.get(r["id"], [])
        cell = (
            "<br>".join(f"`{n}`" for n in sorted(names))
            if names
            else ("—" if r["verification"] != "test" else "**none yet**")
        )
        title = r["title"].replace("|", "\\|")
        lines.append(
            f"| {r['id']} | {title} | {r['priority']} | {r['verification']} | "
            f"{r.get('design', '')} | {r['status']} | {cell} |"
        )
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    reqs = yaml.safe_load(REQUIREMENTS.read_text(encoding="utf-8"))["requirements"]
    content = render(reqs, collect())
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != content:
            print(
                "TRACEABILITY.md is out of date; run scripts/gen_traceability.py", file=sys.stderr
            )
            return 1
        return 0
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
