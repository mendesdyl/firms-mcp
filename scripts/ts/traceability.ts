/**
 * Requirements traceability (ADR-0008, ADR-0012). Reads docs/project/requirements.yaml and the
 * `[REQ-<ID>]` tags in vitest test names, then:
 *
 * - checks the requirements file is well formed;
 * - checks every tag names a known requirement;
 * - checks every requirement verified by `test` whose status is `implemented` or `verified`
 *   has at least one test;
 * - writes docs/project/TRACEABILITY.md, or with `--check` fails if it is out of date.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { parse } from "yaml";

const ROOT = join(import.meta.dirname, "..", "..");
const REQUIREMENTS = join(ROOT, "docs", "project", "requirements.yaml");
const MATRIX = join(ROOT, "docs", "project", "TRACEABILITY.md");
const TEST_DIR = join(ROOT, "test");

const ID_PATTERN = /^(FR-[A-Z]+|SEC|NFR|DOC|PRJ)(-[0-9]{3}|-[A-Z]+-[0-9]{3})$/;
const FIELDS = ["id", "title", "source", "rationale", "priority", "verification", "status"];
const PRIORITIES = new Set(["must", "should", "could"]);
const VERIFICATIONS = new Set(["test", "inspection", "demonstration", "analysis"]);
const STATUSES = new Set(["planned", "implemented", "verified", "deferred"]);

export interface Requirement {
  id: string;
  title: string;
  priority: string;
  verification: string;
  design?: string;
  status: string;
}

export function loadRequirements(text: string): Requirement[] {
  const data = parse(text) as { requirements: Record<string, unknown>[] };
  const problems: string[] = [];
  const seen = new Set<string>();
  for (const r of data.requirements) {
    const id = String(r.id);
    for (const field of FIELDS) if (!(field in r)) problems.push(`${id}: missing ${field}`);
    if (!ID_PATTERN.test(id)) problems.push(`bad requirement ID ${id}`);
    if (seen.has(id)) problems.push(`duplicate requirement ID ${id}`);
    seen.add(id);
    if (!PRIORITIES.has(String(r.priority))) problems.push(`${id}: bad priority ${r.priority}`);
    if (!VERIFICATIONS.has(String(r.verification))) {
      problems.push(`${id}: bad verification ${r.verification}`);
    }
    if (!STATUSES.has(String(r.status))) problems.push(`${id}: bad status ${r.status}`);
  }
  if (problems.length > 0) throw new Error(`requirements.yaml:\n  ${problems.join("\n  ")}`);
  return data.requirements as unknown as Requirement[];
}

/** Test names, keyed by requirement ID, found in `it(...)` / `test(...)` titles. */
export function collectTags(files: { path: string; text: string }[]): Map<string, string[]> {
  const tags = new Map<string, string[]>();
  const call = /\b(?:it|test)(?:\.each\([^)]*\))?\(\s*(["'`])((?:(?!\1)[^\\]|\\.)*)\1/g;
  for (const { path, text } of files) {
    for (const match of text.matchAll(call)) {
      const title = match[2] ?? "";
      for (const tag of title.matchAll(/\[REQ-([A-Z0-9-]+)\]/g)) {
        const id = tag[1] ?? "";
        const name = `${path} › ${title.replace(/\s*\[REQ-[A-Z0-9-]+\]/g, "").trim()}`;
        tags.set(id, [...(tags.get(id) ?? []), name]);
      }
    }
  }
  return tags;
}

export function checkTraceability(requirements: Requirement[], tags: Map<string, string[]>) {
  const known = new Set(requirements.map((r) => r.id));
  const unknown = [...tags.keys()].filter((id) => !known.has(id)).sort();
  const untested = requirements
    .filter((r) => r.verification === "test" && ["implemented", "verified"].includes(r.status))
    .filter((r) => !tags.has(r.id))
    .map((r) => r.id);
  return { unknown, untested };
}

export function renderMatrix(requirements: Requirement[], tags: Map<string, string[]>): string {
  const count = (status: string) => requirements.filter((r) => r.status === status).length;
  const lines = [
    "# Requirements Traceability Matrix",
    "",
    "Generated by `npm run traceability` from [`requirements.yaml`](requirements.yaml) and the",
    "`[REQ-<ID>]` tags in the TypeScript test names under `test/`. Do not edit by hand; run the",
    "script after changing requirements or tests. Iteration 1's Python matrix is preserved at",
    "tag `v0-iteration-1`.",
    "",
    `**Requirements:** ${requirements.length} · **with at least one test:** ${requirements.filter((r) => tags.has(r.id)).length} · ` +
      `**implemented:** ${count("implemented") + count("verified")} · **planned:** ${count("planned")} · **deferred:** ${count("deferred")}`,
    "",
    "| ID | Requirement | Priority | Verification | Design | Status | Tests |",
    "|---|---|---|---|---|---|---|",
  ];
  for (const r of requirements) {
    const tests = (tags.get(r.id) ?? [])
      .sort()
      .map((t) => `\`${t.replaceAll("|", "\\|")}\``)
      .join("<br>");
    lines.push(
      `| ${r.id} | ${r.title.replaceAll("|", "\\|")} | ${r.priority} | ${r.verification} | ${r.design ?? ""} | ${r.status} | ${tests} |`,
    );
  }
  return `${lines.join("\n")}\n`;
}

function testFiles(dir: string): { path: string; text: string }[] {
  return readdirSync(dir, { recursive: true, encoding: "utf8" })
    .filter((name) => name.endsWith(".test.ts"))
    .sort()
    .map((name) => ({
      path: relative(ROOT, join(dir, name)),
      text: readFileSync(join(dir, name), "utf8"),
    }));
}

function main(): void {
  const requirements = loadRequirements(readFileSync(REQUIREMENTS, "utf8"));
  const tags = collectTags(testFiles(TEST_DIR));
  const { unknown, untested } = checkTraceability(requirements, tags);
  const failures = [
    ...(unknown.length ? [`tests tag unknown requirement IDs: ${unknown.join(", ")}`] : []),
    ...(untested.length ? [`implemented requirements without tests: ${untested.join(", ")}`] : []),
  ];
  const matrix = renderMatrix(requirements, tags);
  if (process.argv.includes("--check")) {
    if (readFileSync(MATRIX, "utf8") !== matrix) {
      failures.push("docs/project/TRACEABILITY.md is out of date: run `npm run traceability`");
    }
  } else {
    writeFileSync(MATRIX, matrix);
  }
  if (failures.length > 0) {
    console.error(failures.join("\n"));
    process.exit(1);
  }
  console.error(`traceability ok: ${requirements.length} requirements, ${tags.size} tagged`);
}

if (process.argv[1] === import.meta.filename) main();
